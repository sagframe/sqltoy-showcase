-- ds1 schema: its own transaction-log tables, so hash-sharded rows land in a visibly different database
-- (an empty staff table proves business tables stay on ds0 — see MultiDataSourceTest)

CREATE TABLE IF NOT EXISTS SQLTOY_STAFF_INFO (
    STAFF_ID   VARCHAR(22) NOT NULL,
    STAFF_CODE VARCHAR(22),
    STAFF_NAME VARCHAR(30),
    ORGAN_ID   VARCHAR(8),
    SEX_TYPE   CHAR(1),
    ENTRY_DATE DATE,
    EMAIL      VARCHAR(60),
    CREATE_BY  VARCHAR(22),
    CREATE_TIME TIMESTAMP,
    UPDATE_BY  VARCHAR(22),
    UPDATE_TIME TIMESTAMP,
    STATUS     INT DEFAULT 1,
    CONSTRAINT PK_STAFF PRIMARY KEY (STAFF_ID)
);

CREATE TABLE IF NOT EXISTS SQLTOY_TRANS_LOG_15D (
    TRANS_ID    VARCHAR(32) NOT NULL,
    USER_ID     VARCHAR(32) NOT NULL,
    TRANS_AMT   DECIMAL(12, 2),
    TRANS_DATE  DATE,
    CREATE_BY   VARCHAR(22),
    CREATE_TIME TIMESTAMP,
    UPDATE_BY   VARCHAR(22),
    UPDATE_TIME TIMESTAMP,
    STATUS      INT DEFAULT 1,
    CONSTRAINT PK_TRANS_15D PRIMARY KEY (TRANS_ID)
);

CREATE TABLE IF NOT EXISTS SQLTOY_TRANS_LOG_HIS (
    TRANS_ID    VARCHAR(32) NOT NULL,
    USER_ID     VARCHAR(32) NOT NULL,
    TRANS_AMT   DECIMAL(12, 2),
    TRANS_DATE  DATE,
    CREATE_BY   VARCHAR(22),
    CREATE_TIME TIMESTAMP,
    UPDATE_BY   VARCHAR(22),
    UPDATE_TIME TIMESTAMP,
    STATUS      INT DEFAULT 1,
    CONSTRAINT PK_TRANS_HIS PRIMARY KEY (TRANS_ID)
);

