-- ds0 schema: staff/organ for link & tenant demos, secure-case, tree table, transaction log tables
-- standard audit columns on every business table: CREATE_BY, CREATE_TIME, UPDATE_BY, UPDATE_TIME, STATUS

CREATE TABLE IF NOT EXISTS SQLTOY_ORGAN_INFO (
    ORGAN_ID   VARCHAR(8)  NOT NULL,
    ORGAN_NAME VARCHAR(60),
    SHOW_INDEX INT DEFAULT 0,
    CREATE_BY  VARCHAR(22),
    CREATE_TIME TIMESTAMP,
    UPDATE_BY  VARCHAR(22),
    UPDATE_TIME TIMESTAMP,
    STATUS     INT DEFAULT 1,
    CONSTRAINT PK_ORGAN PRIMARY KEY (ORGAN_ID)
);

CREATE TABLE IF NOT EXISTS SQLTOY_STAFF_INFO (
    STAFF_ID   VARCHAR(22) NOT NULL,
    STAFF_CODE VARCHAR(22),
    STAFF_NAME VARCHAR(30),
    ORGAN_ID   VARCHAR(8),
    SEX_TYPE   CHAR(1),
    ENTRY_DATE DATE,
    EMAIL      VARCHAR(60),
    CREATE_BY  VARCHAR(22),
    CREATE_TIME TIMESTAMP,
    UPDATE_BY  VARCHAR(22),
    UPDATE_TIME TIMESTAMP,
    STATUS     INT DEFAULT 1,
    CONSTRAINT PK_STAFF PRIMARY KEY (STAFF_ID)
);

-- Security demo: @SecureConfig on the entity encrypts tel_no/address on save (ciphertext
-- needs the longer column) and derives tel_mask — a masked search index, because ciphertext
-- itself cannot be searched with LIKE. Reads decrypt automatically.
CREATE TABLE IF NOT EXISTS SQLTOY_SECURE_CASE (
    STAFF_ID   VARCHAR(22) NOT NULL,
    STAFF_NAME VARCHAR(30),
    TEL_NO     VARCHAR(500),
    TEL_MASK   VARCHAR(30),
    ADDRESS    VARCHAR(500),
    CREATE_BY  VARCHAR(22),
    CREATE_TIME TIMESTAMP,
    UPDATE_BY  VARCHAR(22),
    UPDATE_TIME TIMESTAMP,
    STATUS     INT DEFAULT 1,
    CONSTRAINT PK_SECURE PRIMARY KEY (STAFF_ID)
);

-- tree table: NODE_ROUTE/NODE_LEVEL/IS_LEAF are maintained by wrapTreeTableRoute on save
CREATE TABLE IF NOT EXISTS SQLTOY_TREE_NODE (
    NODE_ID    VARCHAR(10) NOT NULL,
    PID        VARCHAR(10),
    NODE_NAME  VARCHAR(30),
    VALUE_CNT  INT DEFAULT 0,
    NODE_ROUTE VARCHAR(200),
    NODE_LEVEL INT,
    IS_LEAF    INT,
    CREATE_BY  VARCHAR(22),
    CREATE_TIME TIMESTAMP,
    UPDATE_BY  VARCHAR(22),
    UPDATE_TIME TIMESTAMP,
    STATUS     INT DEFAULT 1,
    CONSTRAINT PK_TREE_NODE PRIMARY KEY (NODE_ID)
);

-- transaction log: queries are written against the 15d table;
-- the realHisTable strategy routes older dates to SQLTOY_TRANS_LOG_HIS
CREATE TABLE IF NOT EXISTS SQLTOY_TRANS_LOG_15D (
    TRANS_ID    VARCHAR(32) NOT NULL,
    USER_ID     VARCHAR(32) NOT NULL,
    TRANS_AMT   DECIMAL(12, 2),
    TRANS_DATE  DATE,
    CREATE_BY   VARCHAR(22),
    CREATE_TIME TIMESTAMP,
    UPDATE_BY   VARCHAR(22),
    UPDATE_TIME TIMESTAMP,
    STATUS      INT DEFAULT 1,
    CONSTRAINT PK_TRANS_15D PRIMARY KEY (TRANS_ID)
);

CREATE TABLE IF NOT EXISTS SQLTOY_TRANS_LOG_HIS (
    TRANS_ID    VARCHAR(32) NOT NULL,
    USER_ID     VARCHAR(32) NOT NULL,
    TRANS_AMT   DECIMAL(12, 2),
    TRANS_DATE  DATE,
    CREATE_BY   VARCHAR(22),
    CREATE_TIME TIMESTAMP,
    UPDATE_BY   VARCHAR(22),
    UPDATE_TIME TIMESTAMP,
    STATUS      INT DEFAULT 1,
    CONSTRAINT PK_TRANS_HIS PRIMARY KEY (TRANS_ID)
);

