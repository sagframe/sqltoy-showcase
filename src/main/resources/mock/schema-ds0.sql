-- cascade demo: head/item linked by (TRANS_DATE, TRANS_CODE) -> (TRANS_DATE, TRANS_ID)
CREATE TABLE IF NOT EXISTS SQLTOY_CASCADE_HEAD (
    TRANS_DATE  DATE NOT NULL,
    TRANS_CODE  VARCHAR(30) NOT NULL,
    TOTAL_CNT   DECIMAL(12, 3),
    TOTAL_AMT   DECIMAL(12, 2),
    CREATE_BY   VARCHAR(22),
    CREATE_TIME TIMESTAMP,
    UPDATE_BY   VARCHAR(22),
    UPDATE_TIME TIMESTAMP,
    STATUS      INT DEFAULT 1,
    CONSTRAINT PK_CAS_HEAD PRIMARY KEY (TRANS_DATE, TRANS_CODE)
);

CREATE TABLE IF NOT EXISTS SQLTOY_CASCADE_ITEM (
    ID          VARCHAR(32) NOT NULL,
    TRANS_DATE  DATE,
    TRANS_ID    VARCHAR(30),
    PRODUCT_ID  VARCHAR(32),
    QUANTITY    DECIMAL(8, 3),
    PRICE       DECIMAL(8, 2),
    AMT         DECIMAL(10, 2),
    CREATE_BY   VARCHAR(22),
    CREATE_TIME TIMESTAMP,
    UPDATE_BY   VARCHAR(22),
    UPDATE_TIME TIMESTAMP,
    STATUS      INT DEFAULT 1,
    CONSTRAINT PK_CAS_ITEM PRIMARY KEY (ID)
);

